/**
 * Generate the token layer from `src/data/theme/presets.json` and the vendored
 * Basecoat `base.css`:
 *
 *   src/data/theme/generated/tokens.css    :root / .dark defaults (Basecoat's own palette), Tailwind engine subset (--mono-*),
 *                                          mode tokens, mono's control scale
 *   src/data/theme/generated/presets.css   .theme-color-<name> light + dark blocks
 *   src/data/theme/generated/legacy.css    the pre-Basecoat --theme-* vocabulary, alive
 *                                          until 3.0 (aliases where value-identical, the
 *                                          old literal otherwise, -rgb triplets per mode)
 *
 *   node scripts/theme-build.mjs           write
 *   node scripts/theme-build.mjs --check   exit 1 if the committed output is stale
 *
 * Two CSS facts every emitted rule respects:
 *  1. A custom property whose value contains var() is substituted on the element
 *     that DECLARES it. Declared only on :root it goes stale as soon as a
 *     `.theme-color-*` or `.dark` class on <body> overrides the base token. So
 *     every var()-bearing token is emitted on the SCOPES rule below, which
 *     matches every element a preset/mode class can land on.
 *  2. Basecoat's `dark:` variants compile to `&:is(html.dark *)`, which cannot
 *     match inside a shadow root. Mode differences therefore travel only as
 *     inherited custom properties (`--mono-mode-*`), never as selectors.
 */
