/** Fill every derivable slot of a light palette. */
function completeLight(p) {
  const o = { ...p }
  o.card ??= '#ffffff'
  o.popover ??= o.card
  o.muted ??= o.card
  o.secondary ??= o.muted
  o.accent ??= o.muted
  o.input ??= o.border
  o.ring ??= o.primary
  o.cardForeground ??= o.foreground
  o.popoverForeground ??= o.foreground
  o.secondaryForeground ??= o.foreground
  o.accentForeground ??= o.foreground
  o.mutedForeground ??= over(`rgba(${round8(parse(o.foreground)).join(', ')}, 0.6)`, o.background)
  // Light mode keeps the pre-Basecoat convention: white ink on every saturated fill,
  // contrast-picked only for the three slots that were always too light for it.
  for (const k of ['primary', 'destructive', ...ROLES]) {
    o[`${k}Foreground`] ??= ['warning', 'teal', 'neutral'].includes(k) ? ink(o[k]) : INK_LIGHT
  }
  for (let i = 1; i <= 5; i++) o[`chart${i}`] ??= tone(o.primary, { L: 0.86 - (i - 1) * 0.125, Cmax: 0.16 })
  return o
}

/**
 * Basecoat's own light→dark deltas (base.css), applied to a branded palette:
 * neutrals drop to Basecoat's lightness steps keeping a whisper of the brand
 * hue; the brand and status hues are lifted so they read on a dark ground.
 */
function deriveDark(l) {
  const d = {}
  d.background = tone(l.background, { L: 0.145, Cmax: 0.02 })
  d.foreground = tone(l.foreground, { L: 0.985, Cmax: 0.01 })
  d.card = tone(l.background, { L: 0.205, Cmax: 0.02 })
  d.popover = d.card
  d.muted = tone(l.background, { L: 0.269, Cmax: 0.02 })
  d.secondary = d.muted
  d.accent = tone(l.background, { L: 0.371, Cmax: 0.02 })
  d.mutedForeground = tone(l.foreground, { L: 0.708, Cmax: 0.02 })
  d.border = 'rgba(255, 255, 255, 0.10)'
  d.input = 'rgba(255, 255, 255, 0.15)'
  d.primary = tone(l.primary, { L: Math.max(rgbToOklch(parse(l.primary)).L, 0.75) })
  d.ring = tone(l.ring, { L: 0.556, Cmax: 0.12 })
  d.destructive = tone(l.destructive, { L: Math.max(rgbToOklch(parse(l.destructive)).L, 0.704) })
  for (const k of ROLES) {
    const L = rgbToOklch(parse(l[k])).L
    // `dark` flips like `primary` does: it is the strong neutral AGAINST the page,
    // and as outline / text ink a near-black on a near-black ground is unreadable
    // (a solid one read as disabled). `neutral` keeps its mid grey with WHITE ink —
    // lifting it to L 0.708 with dark ink made it a dead ringer for a disabled
    // primary (which is exactly that grey at 50% opacity).
    d[k] = k === 'dark' ? tone(l[k], { L: 0.87, Cmax: 0.02 })
      : k === 'neutral' ? tone(l[k], { L: Math.min(Math.max(L, 0.55), 0.6) })
      : tone(l[k], { L: Math.max(L, 0.7) })
  }
  return d
}

function completeDark(light, dark) {
  const base = deriveDark(light)
  const o = { ...base, ...dark }
  o.popover ??= o.card
  o.cardForeground ??= o.foreground
  o.popoverForeground ??= o.foreground
  o.secondaryForeground ??= o.foreground
  o.accentForeground ??= o.foreground
  // neutral keeps white ink in dark mode (see deriveDark); the rest are contrast-picked
  o.neutralForeground ??= INK_LIGHT
  for (const k of ['primary', 'destructive', ...ROLES]) o[`${k}Foreground`] ??= ink(o[k])
  for (let i = 1; i <= 5; i++) o[`chart${i}`] ??= tone(o.primary, { L: 0.86 - (i - 1) * 0.125, Cmax: 0.16 })
  return o
}

/* ───────────────────────── vendor base.css reader ─────────────────────── */

function readVendorBase() {
  const css = postcss.parse(fs.readFileSync(VENDOR_BASE, 'utf8'))
  const blocks = { ':root': {}, '.dark': {}, '@theme': {} }
  css.walk((node) => {
    if (node.type === 'rule' && blocks[node.selector]) {
      node.each((d) => { if (d.type === 'decl' && d.prop.startsWith('--')) blocks[node.selector][d.prop] = d.value })
    } else if (node.type === 'atrule' && node.name === 'theme') {
      node.each((d) => { if (d.type === 'decl') blocks['@theme'][d.prop] = d.value })
    }
  })
  return blocks
}

/* ────────────────────────────── emission ──────────────────────────────── */

function decl(name, value) {
  return `  ${name}: ${value};\n`
}
function rule(selector, body) {
  return body.trim() ? `${selector} {\n${body}}\n` : ''
}

