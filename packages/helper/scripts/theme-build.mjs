/** Colour tokens of one mode as `--name: oklch(...)` lines. */
function paletteDecls(p, keys) {
  let out = ''
  for (const k of keys) if (p[k] !== undefined) out += decl(cssName(k), oklch(p[k]))
  for (const k of ROLES) {
    out += decl(`--${k}`, oklch(p[k]))
    out += decl(`--${k}-foreground`, oklch(p[`${k}Foreground`]))
  }
  return out
}

