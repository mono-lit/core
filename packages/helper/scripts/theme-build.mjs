const sameColour = (a, b) => round8(parse(a)).join() === round8(parse(b)).join() && parse(a).a === parse(b).a

/**
 * One preset's legacy declarations for one mode.
 *  - old slot value-identical to the new token → omitted (the SCOPES alias covers it)
 *  - otherwise the verbatim old literal (secondary/accent always; material's rgba text)
 *  - `-rgb` triplets: verbatim in light; from the dark palette in dark
 *  - every other old `--theme-*` line the preset declared (tones, MUI action alphas, pillars)
 */
function legacyDecls(preset, palette, mode) {
  const legacy = preset.legacy ?? {}
  let out = ''
  if (mode === 'light') {
    for (const slot of LEGACY_SLOTS) {
      const old = legacy[`--theme-${slot}`]
      const alias = LEGACY_ALIAS[slot]
      if (old === undefined) {
        // No history (the `basecoat` preset): the two meaning-changed slots need a literal.
        if (slot === 'secondary') out += decl('--theme-secondary', oklch(palette.info))
        if (slot === 'accent') out += decl('--theme-accent', oklch(palette.ring))
        continue
      }
      if (alias && sameColour(old, palette[alias])) continue
      out += decl(`--theme-${slot}`, old)
    }
    for (const slot of RGB_SLOTS) {
      const key = `--theme-${slot}-rgb`
      out += decl(key, legacy[key] ?? rgbTriple(slot, palette, legacy))
    }
    for (const [name, value] of Object.entries(legacy)) {
      if (LEGACY_SLOTS.includes(name.replace('--theme-', ''))) continue
      if (name.endsWith('-rgb')) continue
      out += decl(name, value)
    }
  } else {
    for (const slot of RGB_SLOTS) out += decl(`--theme-${slot}-rgb`, rgbTriple(slot, palette, {}))
  }
  return out
}

function rgbTriple(slot, palette, legacy) {
  const alias = LEGACY_ALIAS[slot]
  const source = alias ? palette[alias]
    : slot === 'secondary' ? (legacy['--theme-secondary'] ?? palette.info)
    : (legacy['--theme-accent'] ?? palette.ring)
  return round8(parse(source)).join(', ')
}

/* ──────────────────────────────── build ───────────────────────────────── */

export function build() {
  const presets = JSON.parse(fs.readFileSync(PRESETS, 'utf8'))
  const vendor = readVendorBase()
  const names = Object.keys(presets).filter((k) => !k.startsWith('$'))

  // Resolve every preset to a complete light + dark palette.
  const resolved = {}
  for (const name of names) {
    const p = presets[name]
    if (p.vendor) {
      const fromVendor = (block) => {
        const o = {}
        for (const k of [...SEMANTIC, ...SIDEBAR]) {
          const v = block[cssName(k)]
          if (v && !v.startsWith('url(')) o[k] = v
        }
        return o
      }
      const light = completeLight({ ...fromVendor(vendor[':root']), ...p.light })
      const dark = completeDark(light, { ...fromVendor(vendor['.dark']), ...p.dark })
      resolved[name] = { light, dark, vendor: true }
    } else {
      const light = completeLight(p.light)
      // `dark: false` = the preset has NO dark mode: under html.dark it keeps its
      // light palette AND its light mode tokens (emitted in its dark block, which
      // out-specifies the :where() scopes rules).
      resolved[name] = p.dark === false
        ? { light, dark: light, noDark: true }
        : { light, dark: completeDark(light, p.dark ?? {}), derivedDark: !p.dark }
    }
  }

  const def = resolved[DEFAULT_PRESET]
  const nonColour = Object.entries(vendor[':root']).filter(([k]) =>
    !SEMANTIC.some((s) => cssName(s) === k) && !SIDEBAR.some((s) => cssName(s) === k) && k !== '--radius')
  const nonColourDark = Object.entries(vendor['.dark']).filter(([k]) =>
    !SEMANTIC.some((s) => cssName(s) === k) && !SIDEBAR.some((s) => cssName(s) === k))

  /* tokens.css */
  let rootBody = decl('color-scheme', 'light') + decl('--radius', vendor[':root']['--radius'])
  rootBody += `  /* Basecoat semantic tokens — the default palette (${DEFAULT_PRESET}) */\n`
  rootBody += paletteDecls(def.light, SEMANTIC)
  rootBody += `  /* Basecoat non-colour tokens (verbatim from vendor base.css) */\n`
  for (const [k, v] of nonColour) if (!hasVar(v)) rootBody += decl(k, v)
  // Font families read through the override hooks set ONLY by @mono-lit/helper/ui/font/*.css
  // (--mono-font-sans / --mono-font-mono on :root): unset → the theme's own family.
  rootBody += decl('--font-sans', `var(--mono-font-sans, ${vendor['@theme']['--font-sans']})`)
  rootBody += decl('--font-mono', `var(--mono-font-mono, ${vendor['@theme']['--font-mono']})`)
  rootBody += `  /* Tailwind engine subset the ported rules read */\n`
  for (const [k, v] of ENGINE) rootBody += decl(k, v)
  rootBody += `  /* mono control / type scale */\n`
  for (const [k, v] of SCALE) rootBody += decl(k, v)
  rootBody += `  /* mode tokens (light) */\n`
  for (const [k, l] of MODE) if (!hasVar(l)) rootBody += decl(k, l)

  // The default preset's dark block. A preset with no dark mode (ONE) keeps its
  // light palette and light mode tokens here, so html.dark is a no-op until a
  // preset that has one (theme-color-basecoat) is applied.
  let darkBody = decl('color-scheme', def.noDark ? 'light' : 'dark')
  darkBody += paletteDecls(def.dark, SEMANTIC)
  for (const [k, v] of def.noDark ? nonColour : nonColourDark) if (!hasVar(v)) darkBody += decl(k, v)
  darkBody += `  /* mode tokens (${def.noDark ? 'light — no dark mode' : 'dark'}) */\n`
  for (const [k, l, d] of MODE) if (!hasVar(def.noDark ? l : d)) darkBody += decl(k, def.noDark ? l : d)

  let scopesBody = `  /* var()-bearing tokens re-derive on every element a preset or mode class can land on */\n`
  for (const [k, v] of nonColour) if (hasVar(v)) scopesBody += decl(k, v)
  for (const [k, v] of ENGINE_DERIVED) scopesBody += decl(k, v)
  for (const [k, v] of SIDEBAR_DERIVED) scopesBody += decl(k, v)
  for (const [k, l] of MODE) if (hasVar(l)) scopesBody += decl(k, l)

  let darkScopesBody = ''
  for (const [k, l, d] of MODE) if (hasVar(def.noDark ? l : d)) darkScopesBody += decl(k, def.noDark ? l : d)

  const tokens = HEADER('token layer') +
    '@layer mono-tokens {\n' +
    rule(':root', rootBody) + rule(DARK_ROOT, darkBody) +
    rule(SCOPES, scopesBody) + rule(DARK_SCOPES, darkScopesBody) +
    '}\n' +
    '@keyframes mono-pulse { 50% { opacity: 0.5; } }\n'

  /* presets.css */
  let presetsCss = HEADER('colour presets') + '@layer mono-tokens {\n'
  for (const name of names) {
    const r = resolved[name]
    const keys = r.vendor ? [...SEMANTIC, ...SIDEBAR] : SEMANTIC
    let light = decl('--radius', vendor[':root']['--radius']) + paletteDecls(r.light, keys)
    if (r.vendor) for (const [k, v] of nonColour) if (!hasVar(v)) light += decl(k, v)
    let dark = paletteDecls(r.dark, keys)
    if (r.vendor) for (const [k, v] of nonColourDark) if (!hasVar(v)) dark += decl(k, v)
    dark = decl('color-scheme', r.noDark ? 'light' : 'dark') + dark
    for (const [k, l, d] of MODE) dark += decl(k, r.noDark ? l : d)
    presetsCss += `/* ${presets[name].displayName}${r.derivedDark ? ' — dark values DERIVED (review in ui/color.md)' : ''}${r.noDark ? ' — NO dark mode: stays light under html.dark' : ''} */\n`
    presetsCss += rule(`.theme-color-${name}`, light)
    presetsCss += rule(`.theme-color-${name}:is(${DARK_ROOT}, ${DARK_ROOT} *)`, dark)
  }
  presetsCss += '}\n'

  /* legacy.css */
  let legacyScopes = ''
  for (const [slot, token] of Object.entries(LEGACY_ALIAS)) legacyScopes += decl(`--theme-${slot}`, `var(--${token})`)
  for (const slot of CONTRAST_SLOTS) legacyScopes += decl(`--theme-${slot}-contrast`, `var(--${slot === 'danger' ? 'destructive' : slot}-foreground)`)
  legacyScopes += `  --theme-secondary-contrast: #ffffff;\n`
  for (const slot of MONO_RGB) legacyScopes += decl(`--mono-${slot}-rgb`, `var(--theme-${slot}-rgb)`)
  legacyScopes += LEGACY_ROOT_DERIVED.replace(/^\n/, '')

  let legacyCss = HEADER('pre-Basecoat --theme-* vocabulary, alive until 3.0') + '@layer mono-tokens {\n'
  // A preset's verbatim legacy line can itself contain var() (ONE's
  // --theme-action-selected); on :root that would go stale under a class, so
  // those lines join the scopes rule instead (after the default formulas, so
  // the preset's own wins).
  const rootLegacy = legacyDecls(presets[DEFAULT_PRESET], def.light, 'light').split('\n').filter(Boolean)
  legacyScopes += rootLegacy.filter((l) => hasVar(l)).map((l) => l + '\n').join('')
  legacyCss += rule(':root', rootLegacy.filter((l) => !hasVar(l)).map((l) => l + '\n').join('') + LEGACY_ROOT_LITERALS.replace(/^\n/, ''))
  legacyCss += rule(DARK_ROOT, legacyDecls(presets[DEFAULT_PRESET], def.dark, 'dark'))
  legacyCss += rule(SCOPES, legacyScopes)
  for (const name of names) {
    legacyCss += rule(`.theme-color-${name}`, legacyDecls(presets[name], resolved[name].light, 'light'))
    legacyCss += rule(`.theme-color-${name}:is(${DARK_ROOT}, ${DARK_ROOT} *)`, legacyDecls(presets[name], resolved[name].dark, 'dark'))
  }
  legacyCss += '}\n'

  return {
    files: { 'tokens.css': tokens, 'presets.css': presetsCss, 'legacy.css': legacyCss },
    resolved,
    names,
  }
}

export function check() {
  const { files } = build()
  const stale = []
  for (const [name, text] of Object.entries(files)) {
    const file = path.join(OUT_DIR, name)
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n') : ''
    if (have !== text) stale.push(name)
  }
  return stale
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  if (process.argv.includes('--check')) {
    const stale = check()
    if (stale.length) {
      console.error(`generated theme files are stale: ${stale.join(', ')} — run \`pnpm theme:build\``)
      process.exit(1)
    }
    console.log('generated theme files are current')
  } else {
    const { files, names } = build()
    fs.mkdirSync(OUT_DIR, { recursive: true })
    for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(OUT_DIR, name), text)
    console.log(`wrote ${Object.keys(files).join(', ')} for ${names.length} presets (default: ${DEFAULT_PRESET}) → ${path.relative(root, OUT_DIR)}`)
    const docs = path.join(root, 'scripts', 'theme-docs.mjs')
    if (fs.existsSync(docs)) {
      const { execFileSync } = await import('node:child_process')
      execFileSync(process.execPath, [docs], { stdio: 'inherit' })
    }
  }
}
