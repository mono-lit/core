/* ───────────────────────────── colour math ────────────────────────────── */

function parse(value) {
  const v = String(value).trim()
  let m = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(v)
  if (m) {
    const n = parseInt(m[1], 16)
    return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255, a: m[2] ? parseInt(m[2], 16) / 255 : 1 }
  }
  m = /^#([0-9a-f]{3})$/i.exec(v)
  if (m) {
    const [r, g, b] = m[1].split('').map((c) => parseInt(c + c, 16))
    return { r, g, b, a: 1 }
  }
  m = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+))?\s*\)$/i.exec(v)
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : +m[4] }
  m = /^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+)(%?))?\s*\)$/i.exec(v)
  if (m) {
    const a = m[4] === undefined ? 1 : m[5] ? +m[4] / 100 : +m[4]
    return { ...oklchToRgb(+m[1], +m[2], +m[3]), a }
  }
  throw new Error(`theme-build: cannot parse colour "${value}"`)
}

const lin = (c) => ((c /= 255) <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
const gam = (c) => 255 * (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055)

function rgbToOklab({ r, g, b }) {
  const [lr, lg, lb] = [lin(r), lin(g), lin(b)]
  const l = Math.cbrt(0.4122214708 * lr + 0.5363325363 * lg + 0.0514459929 * lb)
  const m = Math.cbrt(0.2119034982 * lr + 0.6806995451 * lg + 0.1073969566 * lb)
  const s = Math.cbrt(0.0883024619 * lr + 0.2817188376 * lg + 0.6299787005 * lb)
  return {
    L: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    a: 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    b: 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  }
}

function oklabToLinear({ L, a, b }) {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
}

function rgbToOklch(rgb) {
  const { L, a, b } = rgbToOklab(rgb)
  const C = Math.hypot(a, b)
  let H = (Math.atan2(b, a) * 180) / Math.PI
  if (H < 0) H += 360
  return { L, C: C < 1e-4 ? 0 : C, H: C < 1e-4 ? 0 : H }
}

function oklchToRgb(L, C, H) {
  const rad = (H * Math.PI) / 180
  const [r, g, b] = oklabToLinear({ L, a: C * Math.cos(rad), b: C * Math.sin(rad) })
  return { r: gam(r), g: gam(g), b: gam(b) }
}

function inGamut({ r, g, b }) {
  return [r, g, b].every((c) => c >= -0.5 && c <= 255.5)
}

/** Reduce chroma until the colour fits sRGB (Basecoat's own values are all in gamut). */
function clampChroma(L, C, H) {
  if (inGamut(oklchToRgb(L, C, H))) return C
  let lo = 0
  let hi = C
  for (let i = 0; i < 24; i++) {
    const mid = (lo + hi) / 2
    if (inGamut(oklchToRgb(L, mid, H))) lo = mid
    else hi = mid
  }
  return lo
}

const round8 = ({ r, g, b }) => [r, g, b].map((c) => Math.min(255, Math.max(0, Math.round(c))))

/**
 * `oklch(L C H[ / A%])` for a colour, at the fewest decimals that round-trip to
 * the same 8-bit sRGB triple the author wrote — so the port changes the notation,
 * not the pixel.
 */
export function oklch(value) {
  // Already OKLCH (the vendor preset): verbatim — Basecoat's chroma can sit just outside sRGB.
  if (String(value).trim().toLowerCase().startsWith('oklch(')) return String(value).trim()
  const rgb = parse(value)
  const { L, C, H } = rgbToOklch(rgb)
  const want = round8(rgb).join()
  for (let p = 3; p <= 6; p++) {
    const s = { L: +L.toFixed(p), C: +C.toFixed(p), H: +H.toFixed(Math.max(2, p - 1)) }
    if (round8(oklchToRgb(s.L, s.C, s.H)).join() === want) return fmt(s, rgb.a)
  }
  throw new Error(`theme-build: ${value} does not round-trip through oklch`)
}

function fmt({ L, C, H }, a = 1) {
  const alpha = a < 1 ? ` / ${Math.round(a * 1000) / 10}%` : ''
  return `oklch(${trim(L)} ${trim(C)} ${trim(H)}${alpha})`
}
const trim = (n) => String(+n)

function toHex({ r, g, b }) {
  return '#' + round8({ r, g, b }).map((c) => c.toString(16).padStart(2, '0')).join('')
}

/** Solid colour of `fg` painted at its alpha over `bg`. */
function over(fg, bg) {
  const f = parse(fg)
  const b = parse(bg)
  const mix = (x, y) => x * f.a + y * (1 - f.a)
  return toHex({ r: mix(f.r, b.r), g: mix(f.g, b.g), b: mix(f.b, b.b) })
}

function luminance({ r, g, b }) {
  const f = (v) => ((v /= 255) <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
}
function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}

const INK_LIGHT = '#ffffff'
const INK_DARK = 'rgba(0, 0, 0, 0.87)'
/** The same rule as `readableInk` in src/composables/color.ts. */
function ink(bg) {
  const c = parse(bg)
  const white = { r: 255, g: 255, b: 255 }
  const darkOver = { r: c.r * 0.13, g: c.g * 0.13, b: c.b * 0.13 }
  return contrast(c, white) >= contrast(c, darkOver) ? INK_LIGHT : INK_DARK
}

/** New colour at the primary's hue with the given lightness / chroma (gamut-clamped). */
function tone(value, { L, C, Cmax }) {
  const o = rgbToOklch(parse(value))
  const c = clampChroma(L, Math.min(C ?? o.C, Cmax ?? Infinity), o.H)
  return toHex(oklchToRgb(L, c, o.H))
}

